def _find_product(needle: str, data: list[dict]) -> dict:
    hits = []
    for x in data:
        blob = _norm(
            " ".join(
                [x.get("name") or ""]
                + (x.get("aliases") or [])
                + ([x.get("article")] if x.get("article") else [])
            )
        )
        if needle in blob:
            hits.append(x)
    if len(hits) != 1:
        raise SystemExit(
            f"needle {needle!r} matched {len(hits)} products (expect 1)"
        )
    return hits[0]


def _resolve_file(d: Path, name: str) -> Path:
    # точное имя
    exact = d / name
    if exact.exists():
        return exact
    # префикс (на случай опечаток/регистра/combining)
    cands = [p for p in d.iterdir() if p.is_file()
             and _norm(p.name) == _norm(name)]
    if cands:
        return cands[0]
    cands = [p for p in d.iterdir()
             if p.is_file() and _norm(p.name).startswith(_norm(name))]
    if not cands:
        raise SystemExit(f"file not found: {d.name}/{name}")
    if len(cands) > 1:
        raise SystemExit(f"ambiguous file {name}: {sorted(p.name for p in cands)}")
    return cands[0]


def _substrate(key: str, note: str, file: str) -> dict:
    return {
        "substrate": key,
        "note": note,
        "source": {"file": file, "note": note},
    }


