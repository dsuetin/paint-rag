def build_role(d: Path, name: str, role: str, main_quote: str,
               substrates: list) -> dict:
    file = _rel(_resolve_file(d, name))
    return {
        "role": role,
        "substrates": [
            _substrate(k, n, file) for k, n in substrates
        ],
        "source": {"file": file, "note": main_quote},
    }


def apply_role(product: dict, needle: str, d: Path, name: str, role: str,
               main_quote: str, substrates: list) -> bool:
    if _find_product(needle, [product] + [None] * 0) is not None:
        pass
    return True


def main() -> int:
    data = json.loads(PRODUCTS_JSON.read_text(encoding="utf-8"))

    assigned = 0
    for needle, d, name, role, main_quote, substrates in ROLES:
        target = _find_product(needle, data)
        role_obj = build_role(d, name, role, main_quote, substrates)
        # валидация через Product до записи
        candidate = copy.deepcopy(target)
        candidate["role"] = role_obj
        Product.model_validate(candidate)
        target["role"] = role_obj
        assigned += 1
        subs = ", ".join(k for k, _ in substrates) or "-"
        print(f"  role {role:<15} {target.get('name')[:34]:<34} -> [{subs}]")

    for x in data:
        Product.model_validate(x)

    tmp = PRODUCTS_JSON.with_suffix(".json.tmp")
    tmp.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    tmp.replace(PRODUCTS_JSON)
    print(f"\nrole set on {assigned}/{len(data)} products")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
