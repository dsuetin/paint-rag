def _norm(s: str) -> str:
    s = (s or "").lower()
    # убрать все комбинированные диакритики (breve / diaeresis / йотация…)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return re.sub(r"[\s\-\_/.()\[\]«\">\u00ae®]", "", s)


